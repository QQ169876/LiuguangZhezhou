package com.fongmi.android.tv.utils;

/**
 * 铁律：涉黄、涉赌、涉毒以及其它明显涉嫌违法的关键词，一律不许送进大模型。
 *
 * 这条是硬门槛，不是可选项——凡是命中这里任何一条的条目，一次请求都不会发出去，
 * 连缓存都不会查，直接当「判不了」退回本地规则。宁可少判一部剧，也不碰一次线。
 * 后面要加词就往 WORDS 里加，别在别处另起一套。
 */
public final class AiGuard {

    /** 命中任意一个就不许问大模型 */
    private static final String[] WORDS = {
        // 涉黄
        "情色", "色情", "成人片", "成人影视", "三级片", "无码", "有码", "毛片", "黄片", "做爱", "性爱", "性交", "口交", "自慰",
        "裸体", "全裸", "脱衣", "露点", "援交", "卖淫", "嫖娼", "妓女", "淫乱", "乱伦", "强奸", "迷奸", "轮奸", "偷拍", "换妻", "群交", "兽交",
        "AV女优", "av女优", "里番", "本子", "肉蒲团", "性奴", "调教", "性虐", "招嫖", "约炮", "一夜情",
        "porn", "PORN", "porno", "xxx", "XXX", "nsfw", "NSFW", "hentai", "Hentai", "sex video", "nude", "NUDE", "erotic",

        // 涉赌
        "赌博", "赌场", "博彩", "六合彩", "地下赌", "网络赌", "赌球", "赌局", "千术", "出千", "赌王争霸", "线上赌", "境外赌",

        // 涉毒
        "毒品", "吸毒", "贩毒", "制毒", "运毒", "冰毒", "海洛因", "大麻", "摇头丸", "可卡因", "罂粟", "白粉", "K粉", "笑气", "注射毒品",

        // 其它明显违法 / 违禁
        "贩卖人口", "拐卖", "洗钱", "走私军火", "买卖枪支", "枪支弹药", "爆炸物", "制爆", "邪教", "恐怖袭击", "恐怖组织",
        "台独", "疆独", "藏独", "港独", "法轮功"
    };

    private AiGuard() {
    }

    /**
     * 这些文本里有没有碰线的词。传进来的应该是要送进模型的所有内容（剧名、备注、站名等）。
     * 只要有一个命中就 true，调用方必须就此打住。
     */
    public static boolean blocked(String... texts) {
        if (texts == null) return false;
        for (String text : texts) {
            if (text == null || text.isEmpty()) continue;
            for (String word : WORDS) {
                if (text.contains(word)) return true;
            }
        }
        return false;
    }
}
